using System.Text.RegularExpressions;
using Xunit;

namespace Sable.Cli.Tests;

public class CatalogGuardedSchemaPreambleSampleCompositionTests
{
    internal const string SampleName = "Sable.Samples.CatalogGuardedSchemaPreamble";
    internal const string Schema = "catalog_guarded_schema_preamble_sample";

    [Fact]
    public async Task AuthenticGuardedSampleHistoryComposesWithoutChangingPreamble()
    {
        var project = ProjectFile();
        Assert.True(File.Exists(project), "The separate pinned producer sample is missing.");
        var directory = Path.Combine(Path.GetDirectoryName(project)!, "sable", "Marten");
        Assert.Equal(Schema, await File.ReadAllTextAsync(Path.Combine(directory, "schema.txt")));
        var initial = Directory.EnumerateFiles(Path.Combine(directory, "migrations"), "*_Initial.sql").Single();
        var source = await File.ReadAllTextAsync(initial);
        Assert.Contains("-- Generated by Sable", source);
        Assert.Matches(@"pg_catalog\s*\.\s*pg_namespace\s+WHERE\s+nspname\s*=\s*'" + Schema + "'", source);
        Assert.Contains("duplicate_schema", source);
        Assert.Contains("unique_violation", source);
        Assert.Matches(@"(?is)CREATE\s+OR\s+REPLACE\s+FUNCTION", source);
        var preamble = Regex.Match(source, @"(?s)\bDO\s+\$\$.*?\$\$;");
        Assert.True(preamble.Success, "Expected the pinned producer's authentic dollar-quoted DO preamble.");
        var composed = await new MartenMigrationManager(new SilentLogger()).CreateMigrationScript(
            project, SableCliConstants.DefaultDatabaseName
        );
        var preambleIndex = composed.IndexOf(preamble.Value, StringComparison.Ordinal);
        var guardIndex = composed.IndexOf("DO $sable$", preambleIndex, StringComparison.Ordinal);
        Assert.True(preambleIndex >= 0);
        Assert.True(guardIndex > preambleIndex);
        Assert.True(Regex.Match(composed, @"(?is)CREATE\s+OR\s+REPLACE\s+FUNCTION").Index > guardIndex);
        Assert.True(composed.IndexOf("INSERT INTO " + Schema, guardIndex, StringComparison.Ordinal) > guardIndex);
    }

    [Fact]
    public void ProducerAndPendingMappingAreExplicitlyPinnedAndIsolated()
    {
        var project = ProjectFile();
        Assert.True(File.Exists(project), "The separate pinned producer sample is missing.");
        Assert.Contains("Include=\"Marten\" Version=\"9.57.0\"", File.ReadAllText(project));
        var program = File.ReadAllText(Path.Combine(Path.GetDirectoryName(project)!, "Program.cs"));
        Assert.Contains("SABLE_CATALOG_GUARDED_SAMPLE_INCLUDE_PENDING_CHANGE", program);
        Assert.Contains("StringComparison.Ordinal", program);
        Assert.Contains("\"1\"", program);
        Assert.Contains(Schema, program);
    }

    internal static string ProjectFile()
    {
        var directory = new DirectoryInfo(AppContext.BaseDirectory);
        while (directory is not null)
        {
            if (File.Exists(Path.Combine(directory.FullName, "Sable.sln")))
            {
                return Path.Combine(directory.FullName, "samples", SampleName, SampleName + ".csproj");
            }
            directory = directory.Parent;
        }
        throw new DirectoryNotFoundException("Sable repository root not found.");
    }

    private sealed class SilentLogger : IConsoleLogger
    {
        public void LogInfo(string message) { }
        public void LogError(string message) { }
    }
}
